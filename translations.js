// Current language (default: browser preference if ru/be, otherwise 'en')
const browserLang = (navigator.language || 'en').toLowerCase().slice(0, 2);
let currentLang = ['ru', 'be'].includes(browserLang) ? browserLang : 'en';

// Switch the page language and update all data-i18n elements.
function switchLanguage(lang) {
  if (!i18n[lang]) lang = 'en';
  currentLang = lang;
  try {
    localStorage.setItem('yakraz-lang', lang);
  } catch {}
  document.documentElement.lang = ['en', 'ru', 'be'].includes(lang)
    ? lang
    : 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });
}

// Load persisted choice first; otherwise use browser preference set above.
try {
  const saved = localStorage.getItem('yakraz-lang');
  if (saved && i18n[saved]) {
    currentLang = saved;
  }
} catch {}
switchLanguage(currentLang);
